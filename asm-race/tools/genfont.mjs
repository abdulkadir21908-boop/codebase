const bytes = [];
const missing = [];
for (let c = 32; c < 96; c++) {
  const ch = String.fromCharCode(c);
  const art = G[ch];
  if (!art) { missing.push(ch); continue; }
  const rows = art.split("|");
  if (rows.length !== 7 || rows.some((r) => r.length !== 5)) {
    throw new Error(`bad glyph "${ch}"`);
  }
  for (let col = 0; col < 5; col++) {
    let b = 0;
    for (let r = 0; r < 7; r++) if (rows[r][col] === "#") b |= 1 << r;
    bytes.push(b);
  }
}
if (missing.length) throw new Error("missing glyphs: " + missing.join(""));

// pretty print, 16 bytes per line
const lines = [];
for (let i = 0; i < bytes.length; i += 16) {
  lines.push("    .byte " + bytes.slice(i, i + 16).map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", "));
}
const out = `# font.inc -- 5x7 pixel font, ASCII 32..95, 5 bytes per glyph (column major).
# Generated by tools/genfont.mjs -- do not edit by hand.
font5x7:
${lines.join("\n")}
`;

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "..", "font.inc"), out);
console.log(`font.inc written: ${bytes.length} bytes, ${bytes.length / 5} glyphs`);
